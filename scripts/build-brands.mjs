/**
 * Extracts only the brand marks the site actually uses into src/data/brands.js,
 * so simple-icons / devicon stay dev-only instead of shipping in the bundle.
 *
 *   node scripts/build-brands.mjs
 *
 * Brands neither package carries (trademark removals) fall back to a monogram
 * tile in the brand's own colour — deliberately not a hand-drawn approximation
 * of a logo we don't have.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const si = require('simple-icons')

/** name -> simple-icons export key */
const FROM_SIMPLE_ICONS = {
  LangChain: 'siLangchain',
  LangGraph: 'siLanggraph',
  Docker: 'siDocker',
  Snowflake: 'siSnowflake',
  'Google Cloud': 'siGooglecloud',
  Google: 'siGoogle',
  Gemini: 'siGooglegemini',
  Streamlit: 'siStreamlit',
  Python: 'siPython',
  FastAPI: 'siFastapi',
  PostgreSQL: 'siPostgresql',
  MySQL: 'siMysql',
  Cisco: 'siCisco',
  HackerRank: 'siHackerrank',
  Coursera: 'siCoursera',
  Git: 'siGit',
  'Scikit-learn': 'siScikitlearn',
  PyTorch: 'siPytorch',
  'TensorFlow Lite': 'siTensorflow',
  Pandas: 'siPandas',
  NumPy: 'siNumpy',
  React: 'siReact',
  TypeScript: 'siTypescript',
  'Three.js': 'siThreedotjs',
  MongoDB: 'siMongodb',
  Redis: 'siRedis',
  Kafka: 'siApachekafka',
}

/** name -> devicon folder + variant (covers AWS/Azure, dropped by simple-icons) */
const FROM_DEVICON = {
  AWS: ['amazonwebservices', 'amazonwebservices-original-wordmark'],
  Azure: ['azure', 'azure-original'],
  'Azure OpenAI': ['azure', 'azure-original'],
  'AWS Academy': ['amazonwebservices', 'amazonwebservices-original-wordmark'],
}

/** Trademark-restricted or absent everywhere: monogram in the brand colour. */
const MONOGRAM = {
  OpenAI: { label: 'AI', hex: '10A37F' },
  Tableau: { label: 'T', hex: 'E97627' },
  'Power BI': { label: 'BI', hex: 'F2C811' },
  Pinecone: { label: 'P', hex: '1C17FF' },
  ChromaDB: { label: 'C', hex: 'FF6B4A' },
  'AWS Bedrock': { label: 'B', hex: 'FF9900' },
  'GCP / Vertex AI': { label: 'V', hex: '4285F4' },
  'App Runner': { label: 'AR', hex: 'FF9900' },
  FAISS: { label: 'F', hex: '0866FF' },
  PaddleOCR: { label: 'OCR', hex: '0F8FFF' },
  'python-pptx': { label: 'PX', hex: 'D24726' },
  SQL: { label: 'SQL', hex: '4479A1' },
  'Microsoft & LinkedIn': { label: 'M', hex: '0A66C2' },
}

const brands = {}

for (const [name, key] of Object.entries(FROM_SIMPLE_ICONS)) {
  const icon = si[key]
  if (!icon) {
    console.warn(`  ! simple-icons missing: ${name} (${key})`)
    continue
  }
  brands[name] = { kind: 'path', d: icon.path, hex: `#${icon.hex}` }
}

for (const [name, [dir, file]] of Object.entries(FROM_DEVICON)) {
  const path = `node_modules/devicon/icons/${dir}/${file}.svg`
  if (!existsSync(path)) {
    console.warn(`  ! devicon missing: ${name} (${path})`)
    continue
  }
  // Keep the inner markup only; the component supplies sizing and viewBox.
  const raw = readFileSync(path, 'utf8')
  const viewBox = raw.match(/viewBox="([^"]+)"/)?.[1] ?? '0 0 128 128'
  const inner = raw
    .replace(/[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*/, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .trim()
  brands[name] = { kind: 'svg', viewBox, inner }
}

for (const [name, { label, hex }] of Object.entries(MONOGRAM)) {
  brands[name] = { kind: 'mono', label, hex: `#${hex}` }
}

const header = `/* GENERATED by scripts/build-brands.mjs — do not edit by hand.
   Sources: simple-icons (CC0), devicon (MIT). Regenerate with:
     npm run brands  */\n\n`

writeFileSync(
  'src/data/brands.js',
  `${header}export const brands = ${JSON.stringify(brands, null, 2)}\n`,
)

const counts = Object.values(brands).reduce((a, b) => {
  a[b.kind] = (a[b.kind] ?? 0) + 1
  return a
}, {})
console.log(`wrote src/data/brands.js — ${Object.keys(brands).length} marks`, counts)
